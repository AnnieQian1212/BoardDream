export function motifFor(title: string): LucideIcon | undefined {
  const words = title
    .toLowerCase()
    .split(/[^a-z]+/)
    .filter(Boolean)
    .reverse();
  for (const word of words) {
    const singular = word.endsWith("s") && word.length > 3 ? word.slice(0, -1) : word;
    for (const [pattern, icon] of WORDS) if (pattern.test(word) || pattern.test(singular)) return icon;
  }
  return undefined;
}
